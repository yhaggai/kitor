import {
  BundledAdapter,
  CatalogSourceType,
  DetectionDigest,
  DetectionEdition,
  DetectionMode,
  DetectionPathStyle,
  InstallTarget,
  LaunchMethod,
  LaunchPreparation,
  LaunchRoot,
  LaunchWorkingDirectory,
  NativePreparation,
  Platform,
  SourceType,
  Store,
  Tag,
  TextNormalization,
} from "@kitor/registry";

/** Generate Rust wire enums from the same values used by Zod and the UI. */
export function rustVocabulary(): string {
  const enums = {
    Platform,
    Tag,
    Store,
    SourceType,
    CatalogSourceType,
    DetectionMode,
    DetectionPathStyle,
    DetectionDigest,
    TextNormalization,
    DetectionEdition,
    LaunchMethod,
    LaunchRoot,
    LaunchWorkingDirectory,
    NativePreparation,
    BundledAdapter,
    InstallTarget,
    LaunchPreparation,
  };
  const defaults: Record<string, string> = {
    DetectionMode: "patterns",
    DetectionPathStyle: "canonical",
    TextNormalization: "exact",
    InstallTarget: "game_directory",
    LaunchMethod: "executable",
    LaunchRoot: "game_directory",
    LaunchWorkingDirectory: "root",
  };
  let result =
    "// Generated by bun run registry:schema. Do not edit.\nuse serde::{Deserialize, Serialize};\n\n";
  for (const [name, values] of Object.entries(enums)) {
    result += `#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize${defaults[name] ? ", Default" : ""})]\npub enum ${name} {\n`;
    for (const [key, value] of Object.entries(values)) {
      const variant = key
        .split("_")
        .map((part) => part[0].toUpperCase() + part.slice(1))
        .join("");
      if (defaults[name] === value) result += "    #[default]\n";
      result += `    #[serde(rename = "${value}")]\n    ${variant},\n`;
    }
    result += "}\n\n";
  }
  result +=
    "impl From<SourceType> for CatalogSourceType {\n    fn from(source: SourceType) -> Self {\n        match source {\n";
  for (const key of Object.keys(SourceType))
    result += `            SourceType::${key} => Self::${key},\n`;
  result += "        }\n    }\n}\n\n";
  result += `impl Platform {
    pub const fn current() -> Self {
        if cfg!(target_os = "windows") { Self::Windows }
        else if cfg!(target_os = "macos") { Self::MacOS }
        else { Self::Linux }
    }
}
`;
  return result;
}
