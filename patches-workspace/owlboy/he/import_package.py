"""Import a locally built Owlboy Hebrew package as game-dependent BSDIFF assets."""
import argparse, hashlib, json, shutil
from pathlib import Path
import bsdiff4
ROOT=Path(__file__).resolve().parent
p=argparse.ArgumentParser();p.add_argument('--package',type=Path,required=True);p.add_argument('--original',type=Path,required=True);p.add_argument('--platform',choices=['osx','windows'],default='osx');a=p.parse_args()
hash=lambda b:hashlib.sha256(b).hexdigest()
plan=json.loads((a.package/'plan.json').read_text());changes=[]
for entry in plan['files']:
 name=entry['path'];data=(a.package/'payload'/name).read_bytes();assert hash(data)==entry['installed_sha256']
 base=name if entry['original_sha256'] else ('Data/Localizations/de.csv' if name in ('Data/Localizations/he.csv','Data/Localizations/hn.csv') else name.replace('/he/SpriteFont1/','/en/SpriteFont1/').replace('/hn/SpriteFont1/','/en/SpriteFont1/') if '/he/SpriteFont1/' in name or '/hn/SpriteFont1/' in name else None)
 change={'path':name,'operation':'modify' if entry['original_sha256'] else 'create','installed_sha256':hash(data)}
 if entry['original_sha256']:change['original_sha256']=entry['original_sha256']
 if base:
  old=(a.original/base).read_bytes()
  if entry['original_sha256']:assert hash(old)==entry['original_sha256']
  output='deltas/'+name+'.bsdiff';content=bsdiff4.diff(old,data)
  assert bsdiff4.patch(old,content)==data
  change['source']={'kind':'bsdiff','path':output,'input':base,'sha256':hash(content)}
 else:
  output='assets/'+name;content=data;change['source']={'kind':'copy','path':output,'sha256':hash(content)}
 # Isolate the Windows nikud edition so the existing macOS package stays valid.
 if a.platform=='windows':
  output='windows/'+output;change['source']['path']=output
 dest=ROOT/output
 dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(content)
 changes.append(change)
version=plan['version'] if 'kitor' in plan['version'] else '0.2.0-beta.2-kitor1'
manifest={'schema_version':1,'scummvm_id':'owlboy','language':'he','version':version,'filename':f'owlboy-he-{version}-{a.platform}.zip','platforms':{a.platform:{'files':changes}}}
(ROOT/f'patch.{a.platform}.candidate.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
print(f'Imported {len(changes)} tracked file changes for {a.platform}.')

if a.platform=='windows':
 embedded=['// Generated by import_package.py; paths are relative to this file.', 'pub const ASSETS: &[(&str, &[u8])] = &[']
 for f in changes:
  path=f['source']['path'];local=path.removeprefix('windows/')
  embedded.append(f'    ("{path}", include_bytes!("{local}")),')
 embedded.append('];')
 (ROOT/'windows/embedded.rs').write_bytes(('\n'.join(embedded)+'\n').encode('utf-8'))
